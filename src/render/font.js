export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

const ROWS = {};
for (const [ch, def] of Object.entries(GLYPHS)) {
  ROWS[ch] = def.split(' ').map((row) => parseInt(row, 2));
}

export function textWidth(str, scale = 1) {
  return (str.length * ADVANCE - 1) * scale;
}

export function drawText(ctx, str, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  const s = String(str).toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const rows = ROWS[s[i]] || ROWS['?'];
    const gx = x + i * ADVANCE * scale;
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r];
      if (!bits) continue;
      for (let c = 0; c < GLYPH_W; c++) {
        if (bits & (16 >> c)) ctx.fillRect(gx + c * scale, y + r * scale, scale, scale);
      }
    }
  }
}

export function drawTextCentered(ctx, str, cx, y, color, scale = 1) {
  drawText(ctx, str, Math.round(cx - textWidth(String(str), scale) / 2), y, color, scale);
}
